@Composable
fun getTranslations(viewModel: DeenTokViewModel): DeenTokTranslations {
    val selectedLanguageStr by viewModel.selectedLanguage.collectAsState()
    val activeLang = remember(selectedLanguageStr) {
        Language.values().firstOrNull { it.displayName == selectedLanguageStr } ?: Language.ENGLISH
    }
    return translationsMap[activeLang] ?: translationsMap[Language.ENGLISH]!!
}

fun AdminTab.getLocalizedTitle(trans: DeenTokTranslations): String {
    return when (this) {
        AdminTab.DASHBOARD -> trans.studioDashboard
        AdminTab.USERS -> trans.adminUsersTab
        AdminTab.CREATORS -> trans.adminCreatorsTab
        AdminTab.VIDEOS -> trans.adminVideosTab
        AdminTab.COMMENTS -> trans.adminCommentsTab
        AdminTab.REPORTS -> trans.adminReportsTab
        AdminTab.CATEGORIES -> trans.adminCategoriesTab
        AdminTab.HASHTAGS -> trans.adminHashtagsTab
